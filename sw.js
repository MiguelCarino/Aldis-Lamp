const PRECACHE = SHELL.concat(BULK);

// The shell has to come from the deploy, not from an HTTP cache that may still
// be holding the previous build's bytes under the same URL.
const fromNetwork = (url) => new Request(url, { cache: 'reload' });

const resolve = (url) => new URL(url, new URL('./', self.location.href)).href;

// Three shipped files already say what the app needs, and they say it because
// the app itself reads them: index.html names the scripts and stylesheets the
// page loads, manifest.webmanifest the icons a launcher will ask for, and
// fonts/carino-fonts.css the faces the stylesheet fetches. Those are the lists
// that go out of step with a cache — a new font weight, a new script tag — so
// the worker reads them back out of the shell it has just fetched and precaches
// whatever the generated lists missed. That is what stops a forgotten run of
// tools/build_sw.py from costing somebody their offline lamp.
//
// Everything here is parsed, not guessed, and confined to plain relative paths
// inside the scope. It only ever widens what install tries to fetch, and it is
// tried in the failure-tolerant pass: a declaration is somebody's statement
// that a file exists, which is not the same as the file existing.
function declared(cache) {
    const read = (url, extract) => cache.match(url)
        .then((hit) => (hit ? hit.text() : ''))
        .then((text) => (text ? extract(text) : []))
        .catch(() => []);

    return Promise.all([
        read('index.html', (text) => Array.from(
            text.matchAll(/<(?:script|link)\b[^>]*\s(?:src|href)\s*=\s*["']([^"']+)["']/gi),
            (m) => m[1])),
        read('manifest.webmanifest', (text) => {
            const manifest = JSON.parse(text);
            const icons = (manifest.icons || []).map((icon) => icon.src);
            const shortcuts = (manifest.shortcuts || [])
                .flatMap((s) => (s.icons || []).map((icon) => icon.src));
            return icons.concat(shortcuts);
        }),
        read('fonts/carino-fonts.css', (text) =>
            Array.from(text.matchAll(/url\(\s*["']?\.\/([^)"'\s]+)["']?\s*\)/g), (m) => 'fonts/' + m[1])),
    ]).then((lists) => {
        const base = new URL('./', self.location.href).href;
        const seen = new Set(PRECACHE.map(resolve));
        return lists.flat().filter((url) => {
            if (/^[a-z][a-z0-9+.-]*:|^\/\/|[?#]/i.test(url)) return false;
            const href = resolve(url);
            if (!href.startsWith(base) || seen.has(href)) return false;
            seen.add(href);
            return true;
        });
    });
}

// Always this worker's own generation. While a new build is installing both
// caches exist, and a bare caches.match() would be free to answer the running
// page out of the one belonging to code it has never loaded.
const own = caches.open(VERSION);

// Whoever is open is told a new generation is ready and then left alone. A
// worker that finishes installing while the tab is in the background would
// otherwise sit waiting with nobody aware of it.
const announce = () => self.clients.matchAll({ type: 'window', includeUncontrolled: true })
    .then((clients) => clients.forEach((client) =>
        client.postMessage({ type: 'UPDATE_AVAILABLE', version: VERSION })));

// A first install has nothing to interrupt, so it takes over the moment its
// cache is complete and the app is offline-capable on the visit that installed
// it. An update is the opposite case: somewhere there is a page part-way
// through sending a message, and no deploy is worth interrupting it. That
// worker installs, stays waiting, and announces itself; the page decides when
// to take it, by posting SKIP_WAITING once the user has said so.
self.addEventListener('install', (event) => {
    const updating = Boolean(self.registration.active);
    event.waitUntil(
        own.then((cache) =>
            cache.addAll(SHELL.map(fromNetwork))
                .then(() => declared(cache))
                // Awaited rather than fired and forgotten: work left running
                // after install resolves can be killed when the worker idles.
                .then((extra) => Promise.allSettled(
                    BULK.concat(extra).map((url) => cache.add(fromNetwork(url)))))
                .then(() => (updating ? announce() : self.skipWaiting()))
        )
    );
});

// Claiming matters on a first install, where it is what makes the visit that
// registered the worker an offline-capable one. On an update there is nothing
// left to claim: activation only happens because the page asked for it, and
// taking control fires controllerchange, which is the page's cue to reload.
//
// Caches this worker did not create are not this worker's to delete.
self.addEventListener('activate', (event) => {
    event.waitUntil(
        self.clients.claim()
            .then(() => caches.keys())
            .then((keys) => Promise.all(keys
                .filter((key) => key !== VERSION && key.startsWith('carino-aldis-'))
                .map((key) => caches.delete(key))))
    );
});

// Runtime caching is the net for anything the generated list somehow missed,
// but it is deliberately narrow: same-origin, no query string, never a
// navigation.
function keepable(request, response) {
    if (!response.ok || response.type !== 'basic' || request.mode === 'navigate') return false;
    const url = new URL(request.url);
    return url.origin === self.location.origin && !url.search;
}

self.addEventListener('fetch', (event) => {
    const request = event.request;
    if (request.method !== 'GET') return;
    const navigating = request.mode === 'navigate';

    event.respondWith(own.then((cache) =>
        // A navigation carries whatever the link that produced it carried:
        // ?lang=ja, ?do=strobe from a launcher shortcut, a tracker parameter.
        // Matching those against the shell exactly is how an installed offline
        // app answers its own shortcut with the browser's network-error page.
        cache.match(request, navigating ? { ignoreSearch: true } : undefined).then((hit) => {
            if (hit) return hit;
            return fetch(request).then((response) => {
                if (keepable(request, response)) cache.put(request, response.clone());
                return response;
            }).catch(() =>
                // Offline and not in the cache. A navigation still lands on the
                // app; anything else fails as a failure rather than resolving
                // undefined, which respondWith turns into an opaque error.
                navigating
                    ? cache.match('index.html').then((shell) => shell || Response.error())
                    : Response.error()
            );
        })
    ));
});

// Which required URLs are genuinely in the cache. cache.addAll can only report
// that its fetches resolved; this is the only thing that can say the app will
// actually start with the radio off — which is exactly the claim the page makes
// to the user, so it had better be measured rather than assumed.
function missingFrom(cache, required) {
    return Promise.all(required.map((url) => cache.match(url).then((hit) => (hit ? null : url))))
        .then((results) => results.filter(Boolean));
}

function offlineStatus(cache) {
    return Promise.all([cache.keys(), missingFrom(cache, PRECACHE)]).then(([keys, missing]) => ({
        type: 'OFFLINE_STATUS',
        version: VERSION,
        ready: missing.length === 0,
        required: PRECACHE.length,
        present: PRECACHE.length - missing.length,
        entries: keys.length,
        missing: missing,
    }));
}

function reply(event, message) {
    if (event.ports && event.ports[0]) event.ports[0].postMessage(message);
    else if (event.source) event.source.postMessage(message);
}

self.addEventListener('message', (event) => {
    const message = event.data || {};

    if (message.type === 'SKIP_WAITING') {
        self.skipWaiting();
        return;
    }

    if (message.type !== 'OFFLINE_STATUS') return;

    event.waitUntil(own.then((cache) => offlineStatus(cache).then((status) => {
        reply(event, status);
        // install runs once per VERSION, so a font that failed there is
        // otherwise missing forever. Asking repairs it.
        return status.missing.length
            ? Promise.allSettled(status.missing.map((url) => cache.add(fromNetwork(url))))
            : null;
    })));
});
